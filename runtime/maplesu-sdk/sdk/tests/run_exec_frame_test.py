def run(argv):
    done = subprocess.run(list(map(str, argv)), capture_output=True, text=True, encoding='utf-8', errors='replace')
    if done.returncode:
        raise RuntimeError(f'exit {done.returncode}: {argv}\n{done.stdout}\n{done.stderr}')
    return done.stdout


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def function(text, signature):
    start = text.index(signature)
    brace = text.index('{', start)
    pos, depth = brace + 1, 1
    while depth:
        depth += (text[pos] == '{') - (text[pos] == '}')
        pos += 1
    return text[start:pos]


