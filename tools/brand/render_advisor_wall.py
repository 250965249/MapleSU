"""Render the avatar wall of the MapleSU 用户顾问计划 for the README.

The Manager's About MapleSU dialog and this README share one roster: manager/src/main/assets/maplesu/advisors/
holds members.json and one square picture per member in avatars/, named after its id. From them this script writes

* docs/assets/advisors/wall.svg, the avatar wall in README.md and README.en.md. The author sits in the middle and is
  drawn larger, the special-thanks members wear a maple ring, and avatars shrink the farther they sit from the centre.
  GitHub shows SVG images without scripts or external files, so the pictures are embedded and the motion is CSS: the
  avatars spread out from the centre, then a soft pulse keeps travelling outwards. Viewers who ask for reduced motion
  see the still wall.
* the member tables between the advisor markers in README.md and README.en.md.

    python3 tools/brand/render_advisor_wall.py           # validate the members, then regenerate all three files
    python3 tools/brand/render_advisor_wall.py --check   # fail if any of them is out of date (the unit tests run this)

Only the standard library is needed.
"""

from __future__ import annotations

import argparse
import base64
import json
import math
import re
import struct
import sys
from itertools import groupby
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "manager/src/main/assets/maplesu/advisors"
MEMBERS = ASSETS / "members.json"
WALL = ROOT / "docs/assets/advisors/wall.svg"
READMES = {"zh": ROOT / "README.md", "en": ROOT / "README.en.md"}
TABLE_START = "<!-- advisors:start · generated by tools/brand/render_advisor_wall.py; edit manager/src/main/assets/maplesu/advisors/members.json -->"
TABLE_END = "<!-- advisors:end -->"

GROUPS = ("author", "thanks", "beta")
FIELDS = {"id", "name", "group", "beta", "role", "role_en", "tags", "github", "telegram", "signature"}
ID = re.compile(r"^[a-z0-9][a-z0-9-]*$")
GITHUB = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$")
TELEGRAM = re.compile(r"^[A-Za-z][A-Za-z0-9_]{3,31}$")
AVATAR_SUFFIXES = (".jpg", ".png")
AVATAR_SIDES = (120, 320)
AVATAR_MAX_BYTES = 40 * 1024

#: Tag -> (colour, Simple Icons slug) for the flat-square badges, in the style of the README header. A new tag needs
#: an entry here; pick the technology's own colour and icon, or the maple orange F58B55 for MapleSU's own work.
TAG_BADGES = {
    "UI": ("F58B55", "jetpackcompose"),
    "Kotlin": ("7F52FF", "kotlin"),
    "C++": ("00599C", "cplusplus"),
}

TEXT = {
    "zh": {"header": "| 成员 | 身份 | 介绍 | 主页 |", "author": "作者", "thanks": "特别致谢", "beta": "内测用户"},
    "en": {"header": "| Member | Role | About | Links |", "author": "Author", "thanks": "Special thanks",
           "beta": "Beta tester"},
}

# The wall, in SVG units: lattice pitch, lens radius, and the share of a cell an avatar fills.
PITCH = 104.0
LENS = 245.0
FILL = 0.9
AUTHOR_SCALE = 1.42      # the author in the middle is drawn this much larger; everyone else moves out to make room
FLAT = 0.2               # inside this normalised radius avatars keep their full size
EDGE_SCALE = 0.5         # avatar scale at the lens radius
FADE_END = 1.75          # normalised radius at which avatars would have shrunk away
PADDING = 14.0
SQRT3 = math.sqrt(3)


# ── Members ────────────────────────────────────────────────────────────────────────────────────────────────


def load_members(path: Path = MEMBERS) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))["members"]


def avatar_path(member: dict, directory: Path = ASSETS) -> Path | None:
    for suffix in AVATAR_SUFFIXES:
        path = directory / "avatars" / f"{member.get('id')}{suffix}"
        if path.is_file():
            return path
    return None


def image_size(data: bytes) -> tuple[int, int] | None:
    """Width and height of a PNG or JPEG, or None."""
    if data[:8] == b"\x89PNG\r\n\x1a\n" and len(data) >= 24:
        return struct.unpack(">II", data[16:24])
    if data[:2] != b"\xff\xd8":
        return None
    i = 2
    while i + 9 < len(data) and data[i] == 0xFF:
        marker = data[i + 1]
        if marker == 0xFF:
            i += 1
            continue
        length = struct.unpack(">H", data[i + 2:i + 4])[0]
        if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
            height, width = struct.unpack(">HH", data[i + 5:i + 9])
            return width, height
        i += 2 + length
    return None


def problems(members: list[dict], directory: Path = ASSETS) -> list[str]:
    """Everything in members.json and avatars/ that would break the wall or the tables."""
    if not isinstance(members, list) or not members:
        return ["members.json: no members"]
    found: list[str] = []
    ids: set[str] = set()
    for index, member in enumerate(members):
        if not isinstance(member, dict):
            found.append(f"members[{index}]: not an object")
            continue
        where = f"members[{index}] ({member.get('id', '?')})"
        found.extend(f"{where}: unknown field {key!r}" for key in sorted(set(member) - FIELDS))
        ident = member.get("id")
        if not isinstance(ident, str) or not ID.match(ident):
            found.append(f"{where}: id must be lower-case letters, digits and hyphens")
        elif ident in ids:
            found.append(f"{where}: duplicate id")
        else:
            ids.add(ident)
        if not isinstance(member.get("name"), str) or not member["name"].strip():
            found.append(f"{where}: name is missing")
        if member.get("group") not in GROUPS:
            found.append(f"{where}: group must be one of {', '.join(GROUPS)}")
        if "beta" in member and (member["beta"] is not True or member.get("group") != "thanks"):
            found.append(f"{where}: beta: true only marks a special-thanks member who also tested the beta")
        for key in ("role", "role_en", "signature"):
            if key in member and (not isinstance(member[key], str) or not member[key].strip()):
                found.append(f"{where}: {key} must be a non-empty string")
        if "role_en" in member and "role" not in member:
            found.append(f"{where}: role_en translates role, which is missing")
        tags = member.get("tags", [])
        if not isinstance(tags, list) or not all(isinstance(tag, str) for tag in tags):
            found.append(f"{where}: tags must be a list of strings")
        else:
            found.extend(f"{where}: tag {tag!r} has no badge; add it to TAG_BADGES in tools/brand/render_advisor_wall.py"
                         for tag in tags if tag not in TAG_BADGES)
        if "github" in member and not (isinstance(member["github"], str) and GITHUB.match(member["github"])):
            found.append(f"{where}: github must be a GitHub user name")
        if "telegram" in member and not (isinstance(member["telegram"], str) and TELEGRAM.match(member["telegram"])):
            found.append(f"{where}: telegram must be a Telegram user name without @")
        path = avatar_path(member, directory) if isinstance(ident, str) else None
        if path is None:
            found.append(f"{where}: avatars/{ident}.jpg is missing; the wall only shows members with a picture")
            continue
        data = path.read_bytes()
        size = image_size(data)
        if len(data) > AVATAR_MAX_BYTES:
            found.append(f"{where}: {path.name} is {len(data) // 1024} KiB; the limit is {AVATAR_MAX_BYTES // 1024} KiB")
        if size is None:
            found.append(f"{where}: {path.name} is not a JPEG or PNG image")
        elif size[0] != size[1] or not AVATAR_SIDES[0] <= size[0] <= AVATAR_SIDES[1]:
            found.append(f"{where}: {path.name} is {size[0]} × {size[1]}; avatars are square, "
                         f"{AVATAR_SIDES[0]} to {AVATAR_SIDES[1]} px")
    if sum(1 for m in members if isinstance(m, dict) and m.get("group") == "author") != 1:
        found.append("members.json: exactly one member has the author group")
    folder = directory / "avatars"
    if folder.is_dir():
        found.extend(f"avatars/{path.name}: no member uses this file" for path in sorted(folder.iterdir())
                     if path.is_file() and (path.stem not in ids or path.suffix not in AVATAR_SUFFIXES))
    return found


# ── Layout ─────────────────────────────────────────────────────────────────────────────────────────────────


def shells(count: int) -> list[list[tuple[float, float, float]]]:
    """Cells (x, y, distance) of a pointy-top hexagonal lattice with unit pitch, grouped into shells of equal
    distance from the centre and ordered clockwise from the top."""
    reach = math.ceil(math.sqrt(count)) + 2
    cells = []
    for q in range(-reach, reach + 1):
        for r in range(-reach, reach + 1):
            x, y = q + r / 2, r * SQRT3 / 2
            angle = (math.atan2(x, -y) + 2 * math.pi) % (2 * math.pi)
            cells.append((round(math.hypot(x, y), 6), round(angle, 6), x, y))
    cells.sort(key=lambda cell: (cell[0], cell[1]))
    return [[(x, y, distance) for _, _, x, y in shell] for distance, shell in groupby(cells, key=lambda c: c[0])]


def ordered(members: list[dict]) -> list[dict]:
    """The author, then the special-thanks members, then the beta testers, each in roster order."""
    rank = {group: index for index, group in enumerate(GROUPS)}
    return [m for _, m in sorted(enumerate(members), key=lambda pair: (rank[pair[1]["group"]], pair[0]))]


def spread(count: int, slots: list[int]) -> list[int]:
    """``count`` of ``slots``, as evenly spaced around the shell as they can be."""
    return [slots[k * len(slots) // count] for k in range(count)]


def assign(members: list[dict]) -> list[tuple[dict, float, float, float]]:
    """(member, x, y, ring) on the lattice: the author in the centre, then the special-thanks members, then the
    beta testers, shell by shell. A group that does not fill a shell is spread evenly around it and the next group
    takes the remaining cells; the last, partial shell is spread evenly as a whole."""
    queue = ordered(members)
    placed: list[tuple[dict, float, float, float]] = []
    for shell in shells(len(queue)):
        if not queue:
            break
        take, queue = queue[:len(shell)], queue[len(shell):]
        free = spread(len(take), list(range(len(shell))))
        chosen: dict[int, dict] = {}
        runs = [list(run) for _, run in groupby(take, key=lambda m: m["group"])]
        for run in runs[:-1]:
            picks = spread(len(run), free)
            chosen.update(zip(picks, run))
            free = [slot for slot in free if slot not in picks]
        chosen.update(zip(free, runs[-1]))
        placed.extend((chosen[slot], *shell[slot]) for slot in sorted(chosen))
    return placed


def smooth(t: float) -> float:
    t = min(max(t, 0.0), 1.0)
    return t * t * (3 - 2 * t)


def lens_scale(u: float) -> float:
    if u <= FLAT:
        return 1.0
    if u <= 1:
        return 1 - (1 - EDGE_SCALE) * smooth((u - FLAT) / (1 - FLAT))
    return EDGE_SCALE * (1 - smooth((u - 1) / (FADE_END - 1)))


def lens_radius(u: float, steps: int = 2048) -> float:
    """Where an avatar at normalised radius ``u`` is drawn: the integral of lens_scale, so that neighbours stay as
    close as their sizes allow."""
    h = u / steps
    return sum((lens_scale(i * h) + lens_scale((i + 1) * h)) / 2 * h for i in range(steps))


def layout(members: list[dict]) -> list[tuple[dict, float, float, float, float]]:
    """(member, x, y, radius, ring) in SVG units, centred on the origin, author first."""
    base = PITCH * FILL / 2
    extra = base * (AUTHOR_SCALE - 1)
    out = []
    for member, x, y, ring in assign(members):
        distance = math.hypot(x, y) * PITCH
        if distance == 0:
            out.append((member, 0.0, 0.0, base * AUTHOR_SCALE, 0.0))
            continue
        u = distance / LENS
        drawn = lens_radius(u) * LENS + extra
        out.append((member, x * PITCH / distance * drawn, y * PITCH / distance * drawn, base * lens_scale(u), ring))
    return out


# ── SVG ────────────────────────────────────────────────────────────────────────────────────────────────────

STYLE = """\
.pop{animation:pop 1s cubic-bezier(.2,.8,.3,1.2) both;transform-box:fill-box;transform-origin:center}
.pulse{animation:pulse 6s ease-in-out infinite;transform-box:fill-box;transform-origin:center}
.glow{animation:glow 1.6s ease-out both}
.hair{fill:none;stroke:rgba(0,0,0,.09);stroke-width:1}
@keyframes pop{from{opacity:0;transform:translate(var(--x),var(--y)) scale(.05)}40%{opacity:1}to{opacity:1;transform:translate(0,0) scale(1)}}
@keyframes pulse{0%,16%,100%{transform:scale(1)}6%{transform:scale(1.06)}}
@keyframes glow{from{opacity:0}to{opacity:1}}
@media (prefers-color-scheme:dark){.hair{stroke:rgba(255,255,255,.16)}}
@media (prefers-reduced-motion:reduce){.pop,.pulse,.glow{animation:none}}"""


def number(value: float) -> str:
    text = f"{value:.1f}"
    return "0.0" if text == "-0.0" else text


def escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def avatar_markup(member: dict, radius: float) -> str:
    """An avatar centred on the origin with outer radius ``radius``: ring and picture, or picture and hairline."""
    ring, gap, paint = {"author": (0.11, 0.07, "url(#author)"), "thanks": (0.1, 0.08, "url(#maple)")}.get(
        member["group"], (0.0, 0.0, None))
    ring, gap = radius * ring, radius * gap
    inner = radius - ring - gap
    parts = []
    if paint:
        parts.append(f'<circle r="{number(radius - ring / 2)}" fill="none" stroke="{paint}" '
                     f'stroke-width="{number(ring)}"/>')
    path = avatar_path(member)
    mime = "image/png" if path.suffix == ".png" else "image/jpeg"
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    parts.append(f'<image href="data:{mime};base64,{encoded}" x="{number(-inner)}" y="{number(-inner)}" '
                 f'width="{number(2 * inner)}" height="{number(2 * inner)}" clip-path="url(#round)" '
                 f'preserveAspectRatio="xMidYMid slice"/>')
    if not paint:
        parts.append(f'<circle class="hair" r="{number(inner - 0.5)}"/>')
    return "".join(parts)


def render_svg(members: list[dict]) -> str:
    placed = layout(members)
    half_w = max(abs(x) + r for _, x, _, r, _ in placed) + PADDING
    half_h = max(abs(y) + r for _, _, y, r, _ in placed) + PADDING
    width, height = 2 * half_w, 2 * half_h
    title = (f"MapleSU 用户顾问计划头像墙：{placed[0][0]['name']} 位于中心，"
             f"周围是 {'、'.join(m['name'] for m, *_ in placed[1:])}")
    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{number(-half_w)} {number(-half_h)} {number(width)} '
        f'{number(height)}" width="{round(width)}" height="{round(height)}" role="img" aria-labelledby="title">',
        f'<title id="title">{escape(title)}</title>',
        f"<style>\n{STYLE}\n</style>",
        "<defs>",
        '<clipPath id="round" clipPathUnits="objectBoundingBox"><circle cx=".5" cy=".5" r=".5"/></clipPath>',
        '<linearGradient id="maple" x1="0" y1="0" x2="1" y2="1">'
        '<stop offset="0" stop-color="#FFB05C"/><stop offset="1" stop-color="#D95343"/></linearGradient>',
        '<linearGradient id="author" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#EAC26C"/>'
        '<stop offset=".45" stop-color="#F58B55"/><stop offset="1" stop-color="#D95343"/></linearGradient>',
        '<radialGradient id="glow"><stop offset="0" stop-color="#F58B55" stop-opacity=".26"/>'
        '<stop offset="1" stop-color="#F58B55" stop-opacity="0"/></radialGradient>',
        "</defs>",
        f'<circle class="glow" r="{number(PITCH * 2.4)}" fill="url(#glow)"/>',
    ]
    for member, x, y, radius, ring in placed:
        pop = f"--x:{number(-x)}px;--y:{number(-y)}px;animation-delay:{0.08 + ring * 0.17:.2f}s"
        pulse = f"animation-delay:{1.6 + ring * 0.3:.2f}s"
        lines.append(f'<g transform="translate({number(x)} {number(y)})"><g class="pop" style="{pop}">'
                     f'<g class="pulse" style="{pulse}">{avatar_markup(member, radius)}</g></g></g>')
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


# ── README tables ──────────────────────────────────────────────────────────────────────────────────────────


def markdown(text: str) -> str:
    return re.sub(r"([\\`*_\[\]<>|])", r"\\\1", text)


def badge(tag: str) -> str:
    colour, icon = TAG_BADGES[tag]
    label = quote(tag.replace("-", "--").replace("_", "__"), safe="")
    return f"![{tag}](https://img.shields.io/badge/{label}-{colour}?style=flat-square&logo={icon}&logoColor=white)"


def render_table(members: list[dict], language: str) -> str:
    text = TEXT[language]
    rows = [text["header"], "| --- | --- | --- | --- |"]
    for member in ordered(members):
        groups = [member["group"]] + (["beta"] if member.get("beta") else [])
        role = member.get("role_en" if language == "en" and "role_en" in member else "role")
        about = " ".join(filter(None, [markdown(role) if role else "", " ".join(map(badge, member.get("tags", [])))]))
        if "signature" in member:
            about += ("<br>" if about else "") + f"“{markdown(member['signature'])}”"
        links = [f"[GitHub](https://github.com/{member['github']})"] if "github" in member else []
        links += [f"[Telegram](https://t.me/{member['telegram']})"] if "telegram" in member else []
        rows.append(f"| {markdown(member['name'])} | {' · '.join(text[g] for g in groups)} | {about or '—'} | "
                    f"{' · '.join(links) or '—'} |")
    return "\n".join(rows)


def render_readme(members: list[dict], language: str, current: str) -> str:
    start, end = current.find(TABLE_START), current.find(TABLE_END)
    if start < 0 or end < start:
        raise ValueError(f"{READMES[language].name}: the advisor table markers are missing")
    return current[:start + len(TABLE_START)] + "\n\n" + render_table(members, language) + "\n\n" + current[end:]


# ── Entry point ────────────────────────────────────────────────────────────────────────────────────────────


def outputs(members: list[dict]) -> dict[Path, str]:
    result = {WALL: render_svg(members)}
    for language, path in READMES.items():
        result[path] = render_readme(members, language, path.read_text(encoding="utf-8"))
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only report whether the outputs are current")
    args = parser.parse_args(argv)
    members = load_members()
    found = problems(members)
    if found:
        print("\n".join(found), file=sys.stderr)
        return 1
    stale = {path: text for path, text in outputs(members).items()
             if not path.is_file() or path.read_bytes() != text.encode("utf-8")}
    if args.check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date; run python3 tools/brand/render_advisor_wall.py",
                  file=sys.stderr)
        return 1 if stale else 0
    for path, text in stale.items():
        path.write_bytes(text.encode("utf-8"))
        print(f"wrote {path.relative_to(ROOT)}")
    if not stale:
        print("up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
