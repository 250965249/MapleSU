"""Build the small, freestanding Ultra module filter and embed its audited relocation slots."""
from pathlib import Path
import argparse, base64, hashlib, json, os, re, subprocess, sys, tempfile

ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--llvm', type=Path, help='NDK llvm bin directory; default is the NDK that ANDROID_NDK_HOME or ANDROID_HOME names')
p.add_argument('--check', action='store_true')
args = p.parse_args()
sys.path.insert(0, str(ROOT / 'tools'))
import native_toolchain
args.llvm = args.llvm or native_toolchain.ndk_bin(native_toolchain.ndk_home())
SUFFIX = '.exe' if os.name == 'nt' else ''
src = ROOT / 'tools/ultra-vr-filter'
target = ROOT / 'manager/src/main/java/dev/maplesu/manager/ultrakernel/UltraKernelVivoPayload.kt'
def run(tool, *argv):
    return subprocess.check_output([str(args.llvm / (tool + SUFFIX)), *map(str, argv)], text=True)
with tempfile.TemporaryDirectory(prefix='maplesu-vr-') as tmp:
    work = Path(tmp)
    run('clang', '--target=aarch64-linux-gnu', '-c', '-O2', '-ffreestanding', '-fno-builtin',
        '-fno-stack-protector', '-fno-unwind-tables', '-fno-asynchronous-unwind-tables',
        '-fno-jump-tables', '-fno-vectorize', '-fno-slp-vectorize', '-mgeneral-regs-only',
        '-ffixed-x18', '-mbranch-protection=none', src/'filter.c', '-o', work/'filter.o')
    run('clang', '--target=aarch64-linux-gnu', '-c', src/'entry.S', '-o', work/'entry.o')
    run('ld.lld', '-T', src/'link.ld', '-e', 'vr_entry', '--no-undefined', '-o', work/'filter.elf', work/'entry.o', work/'filter.o')
    relocs = run('llvm-readelf', '-r', work/'filter.elf')
    if 'There are no relocations' not in relocs: raise RuntimeError('VR_PAYLOAD_RELOCATIONS')
    syms = run('llvm-readelf', '-s', work/'filter.elf')
    offsets = {name: int(value, 16) for value, name in re.findall(r'\d+:\s+([0-9a-fA-F]+)\s+\d+\s+\S+\s+\S+\s+\S+\s+\S+\s+(vr_\w+)', syms)}
    run('llvm-objcopy', '-O', 'binary', '--only-section=.text', work/'filter.elf', work/'filter.bin')
    blob = (work/'filter.bin').read_bytes()
    names = ('displaced', 'continue', 'return', 'hdr', 'len', 'compressed', 'release_hdr', 'vfree', 'decompress')
    code = 'package dev.maplesu.manager.ultrakernel\n\n// Generated by scripts/build-ultra-vr-filter.py from tools/ultra-vr-filter/.\ninternal object UltraKernelVivoPayload {\n'
    code += '    const val SHA256 = "' + hashlib.sha256(blob).hexdigest() + '"\n'
    for name in names:
        code += '    const val ' + name.upper() + ' = ' + str(offsets['vr_' + name]) + '\n'
    code += '    fun bytes(): ByteArray = java.util.Base64.getDecoder().decode(\n'
    encoded = base64.b64encode(blob).decode()
    code += ' +\n'.join('        "' + encoded[i:i+100] + '"' for i in range(0, len(encoded), 100)) + ')\n}\n'
    if args.check:
        if target.read_text() != code: raise RuntimeError('VR_PAYLOAD_SOURCE_STALE')
    else: target.write_text(code, encoding='utf-8')
    print(json.dumps(dict(bytes=len(blob), sha256=hashlib.sha256(blob).hexdigest(), offsets=offsets)))
